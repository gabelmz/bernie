/**
 * Companion code generators.
 *
 * When a platform cannot be reached directly from the browser — Google
 * Workspace OAuth is unavailable, or a service-role key must not leave the
 * server — Bernie generates code you deploy *on that platform* instead. The
 * deployment exposes one HTTPS endpoint that Bernie's Custom HTTP Saves
 * connection can pull from and push to, so a workflow keeps working without
 * the blocked credential path.
 *
 * Pure string building, no side effects, so every generator is unit testable.
 */

export type CompanionTarget = 'sheets-apps-script' | 'supabase-edge-function' | 'drive-apps-script';

export interface CompanionFile {
  name: string;
  language: 'javascript' | 'typescript' | 'json' | 'sql';
  contents: string;
}

export interface CompanionBundle {
  target: CompanionTarget;
  title: string;
  /** What this deployment does, in one line. */
  summary: string;
  /** Ordered steps the user follows to deploy it. */
  steps: string[];
  files: CompanionFile[];
  /** How to point Bernie at the deployment once it exists. */
  wireUp: string[];
}

export interface CompanionOptions {
  /** Spreadsheet the Apps Script should bind to. */
  spreadsheetId?: string;
  /** Default tab name. */
  sheetName?: string;
  /** Drive folder the script should read and write. */
  folderId?: string;
  /** Supabase table an Edge Function should write to. */
  table?: string;
  /** Conflict column for upserts. */
  onConflict?: string;
  /** Shared secret the endpoint requires. Generated when absent. */
  sharedSecret?: string;
}

/**
 * A URL-safe shared secret. Uses the Web Crypto API when available so the
 * value is not predictable, and never silently falls back to Math.random
 * without saying so in the generated comment.
 */
export function generateSharedSecret(length = 32): string {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
  const crypto = (globalThis as any).crypto;

  if (crypto?.getRandomValues) {
    const bytes = new Uint8Array(length);
    crypto.getRandomValues(bytes);
    return Array.from(bytes, (byte) => alphabet[byte % alphabet.length]).join('');
  }

  let out = '';
  for (let i = 0; i < length; i += 1) {
    out += alphabet[Math.floor(Math.random() * alphabet.length)];
  }
  return out;
}

function secretOf(options: CompanionOptions): string {
  return String(options.sharedSecret || '').trim() || generateSharedSecret();
}

