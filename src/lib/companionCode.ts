/** Builds the deployable bundle for one target. */
export function generateCompanion(target: CompanionTarget, options: CompanionOptions = {}): CompanionBundle {
  const secret = secretOf(options);

  if (target === 'sheets-apps-script') {
    return {
      target,
      title: 'Google Sheets — Apps Script Web App',
      summary:
        'Reads and writes this spreadsheet from an Apps Script Web App, so Bernie needs no Google OAuth token.',
      steps: [
        'Open the spreadsheet, then Extensions, Apps Script.',
        'Replace the contents of Code.gs with the file below and save.',
        'Deploy, New deployment, type Web app.',
        'Set "Execute as" to Me, and "Who has access" to Anyone with the link.',
        'Deploy, authorize when prompted, and copy the /exec Web App URL.',
      ],
      files: [{ name: 'Code.gs', language: 'javascript', contents: sheetsAppsScript(options, secret) }],
      wireUp: [
        'Open Connections & APIs, Custom HTTP Saves.',
        'Paste the /exec URL as the Base URL and save.',
        'On a Custom HTTP node choose Send a request, method POST, and leave the path blank.',
        `Body: {"secret": "${secret}", "action": "append", "sheet": "${options.sheetName || 'Sheet1'}"} — Bernie appends the incoming rows.`,
        'Use "action": "pull" to read rows instead, or "overwrite" to replace the tab.',
      ],
    };
  }

  if (target === 'drive-apps-script') {
    return {
      target,
      title: 'Google Drive — Apps Script Web App',
      summary: 'Lists a Drive folder and writes files into it without Bernie holding a Google token.',
      steps: [
        'Open script.google.com and create a new project.',
        'Replace Code.gs with the file below and save.',
        'Deploy, New deployment, type Web app.',
        'Set "Execute as" to Me, and "Who has access" to Anyone with the link.',
        'Deploy, authorize when prompted, and copy the /exec Web App URL.',
      ],
      files: [{ name: 'Code.gs', language: 'javascript', contents: driveAppsScript(options, secret) }],
      wireUp: [
        'Open Connections & APIs, Custom HTTP Saves, and paste the /exec URL as the Base URL.',
        `To list files, use a Custom HTTP node with method GET and query {"secret": "${secret}", "limit": 50}.`,
        `To write rows, use method POST and body {"secret": "${secret}", "format": "csv"}.`,
      ],
    };
  }

  return {
    target,
    title: 'Supabase — Edge Function',
    summary:
      'Writes rows with the service role key from inside Supabase, so that privileged key never reaches the browser.',
    steps: [
      'Install the CLI and run: supabase functions new bernie-rows',
      'Replace supabase/functions/bernie-rows/index.ts with the file below.',
      `Set the shared secret: supabase secrets set BERNIE_SECRET=${secret}`,
      'Deploy it: supabase functions deploy bernie-rows',
      'Copy the function URL from the dashboard, Edge Functions.',
    ],
    files: [
      { name: 'index.ts', language: 'typescript', contents: supabaseEdgeFunction(options, secret) },
      {
        name: 'deno.json',
        language: 'json',
        contents: JSON.stringify({ imports: { '@supabase/supabase-js': 'jsr:@supabase/supabase-js@2' } }, null, 2),
      },
    ],
    wireUp: [
      'Either use the Supabase node: choose "Invoke an Edge Function" and set the name to bernie-rows.',
      'Or point Custom HTTP Saves at the function URL and POST to it directly.',
      `Body: {"secret": "${secret}", "action": "upsert", "table": "${options.table || 'rows'}"${
        options.onConflict ? `, "onConflict": "${options.onConflict}"` : ''
      }}`,
      'Supported actions: insert, upsert, select, update, delete. update and delete require filters.',
    ],
  };
}

/** The companion targets available for an integration, if any. */
export function companionTargetsFor(integration: string): CompanionTarget[] {
  switch (integration) {
    case 'sheets':
      return ['sheets-apps-script'];
    case 'drive':
      return ['drive-apps-script'];
    case 'supabase':
      return ['supabase-edge-function'];
    default:
      return [];
  }
}
