function sheetsAppsScript(options: CompanionOptions, secret: string): string {
  const sheetName = options.sheetName || 'Sheet1';
  const spreadsheetId = options.spreadsheetId || '';

  return `/**
 * Bernie companion endpoint for Google Sheets.
 *
 * Deployed as a Web App, this gives Bernie a token-free way to read and write
 * this spreadsheet: Apps Script already runs as you, so no OAuth handshake and
 * no Google API key are involved.
 *
 * Generated by Bernie. Safe to edit.
 */

// Bernie must send this in the "secret" field. Rotate it by changing both here
// and in the Bernie connection.
var BERNIE_SECRET = ${JSON.stringify(secret)};

${spreadsheetId ? `// Bound spreadsheet. Leave blank to use the one this script is attached to.
var SPREADSHEET_ID = ${JSON.stringify(spreadsheetId)};` : `// Blank means "the spreadsheet this script is attached to".
var SPREADSHEET_ID = '';`}
var DEFAULT_SHEET = ${JSON.stringify(sheetName)};

function openSheet_(name) {
  var book = SPREADSHEET_ID
    ? SpreadsheetApp.openById(SPREADSHEET_ID)
    : SpreadsheetApp.getActiveSpreadsheet();
  if (!book) {
    throw new Error('No spreadsheet. Set SPREADSHEET_ID, or bind this script to a sheet.');
  }

  var sheet = book.getSheetByName(name || DEFAULT_SHEET);
  if (!sheet) {
    sheet = book.insertSheet(name || DEFAULT_SHEET);
  }
  return sheet;
}

function json_(payload, status) {
  return ContentService
    .createTextOutput(JSON.stringify(payload))
    .setMimeType(ContentService.MimeType.JSON);
}

function authorize_(params) {
  if (!BERNIE_SECRET) return;
  if (String(params && params.secret) !== BERNIE_SECRET) {
    throw new Error('Unauthorized: the shared secret did not match.');
  }
}

/** Rows out of the sheet, using the header row for keys. */
function readRows_(sheetName, limit) {
  var sheet = openSheet_(sheetName);
  var values = sheet.getDataRange().getValues();
  if (!values.length) return [];

  var headers = values[0].map(function (header, index) {
    var name = String(header || '').trim();
    return name || 'col_' + (index + 1);
  });

  var rows = [];
  var max = limit ? Math.min(Number(limit) + 1, values.length) : values.length;
  for (var i = 1; i < max; i++) {
    var row = {};
    for (var c = 0; c < headers.length; c++) {
      row[headers[c]] = values[i][c];
    }
    rows.push(row);
  }
  return rows;
}

/** Turns rows into a rectangular matrix, header row first. */
function toMatrix_(rows, includeHeaders) {
  if (!rows.length) return [];

  var headers = [];
  rows.forEach(function (row) {
    Object.keys(row).forEach(function (key) {
      if (headers.indexOf(key) === -1) headers.push(key);
    });
  });

  var matrix = includeHeaders === false ? [] : [headers];
  rows.forEach(function (row) {
    matrix.push(headers.map(function (header) {
      var value = row[header];
      if (value === null || value === undefined) return '';
      return typeof value === 'object' ? JSON.stringify(value) : value;
    }));
  });
  return matrix;
}

/**
 * GET pulls rows.
 *   ?secret=...&sheet=Sheet1&limit=10
 */
function doGet(e) {
  try {
    var params = (e && e.parameter) || {};
    authorize_(params);
    var rows = readRows_(params.sheet, params.limit);
    return json_({ ok: true, rows: rows, count: rows.length });
  } catch (err) {
    return json_({ ok: false, error: String(err && err.message ? err.message : err) });
  }
}

/**
 * POST pushes rows, clears a range, or previews.
 *   { secret, action: 'append' | 'overwrite' | 'clear' | 'pull',
 *     sheet: 'Sheet1', rows: [ {...} ], includeHeaders: true, limit: 10 }
 */
function doPost(e) {
  try {
    var body = {};
    if (e && e.postData && e.postData.contents) {
      body = JSON.parse(e.postData.contents);
    }
    authorize_(body);

    var action = String(body.action || 'append');
    var sheetName = body.sheet;

    if (action === 'pull') {
      var pulled = readRows_(sheetName, body.limit);
      return json_({ ok: true, rows: pulled, count: pulled.length });
    }

    var sheet = openSheet_(sheetName);

    if (action === 'clear') {
      sheet.clearContents();
      return json_({ ok: true, action: 'clear', sheet: sheet.getName() });
    }

    var rows = body.rows || [];
    if (!rows.length) {
      return json_({ ok: false, error: 'No rows supplied.' });
    }

    var matrix = toMatrix_(rows, body.includeHeaders);
    if (!matrix.length) {
      return json_({ ok: false, error: 'Rows had no columns.' });
    }

    if (action === 'overwrite') {
      sheet.clearContents();
      sheet.getRange(1, 1, matrix.length, matrix[0].length).setValues(matrix);
    } else {
      // Append below the last row that holds data.
      var startRow = sheet.getLastRow() + 1;
      // Skip the header when the sheet already has content.
      if (startRow > 1 && body.includeHeaders !== false) {
        matrix = matrix.slice(1);
      }
      if (!matrix.length) {
        return json_({ ok: true, action: action, written: 0 });
      }
      sheet.getRange(startRow, 1, matrix.length, matrix[0].length).setValues(matrix);
    }

    return json_({
      ok: true,
      action: action,
      sheet: sheet.getName(),
      written: rows.length
    });
  } catch (err) {
    return json_({ ok: false, error: String(err && err.message ? err.message : err) });
  }
}
`;
}

function driveAppsScript(options: CompanionOptions, secret: string): string {
  const folderId = options.folderId || '';

  return `/**
 * Bernie companion endpoint for Google Drive.
 *
 * Deployed as a Web App, this lists a folder and writes files into it without
 * Bernie holding a Google OAuth token.
 *
 * Generated by Bernie. Safe to edit.
 */

var BERNIE_SECRET = ${JSON.stringify(secret)};
${folderId ? `var FOLDER_ID = ${JSON.stringify(folderId)};` : `// Blank means the script's own Drive root.
var FOLDER_ID = '';`}

function folder_() {
  return FOLDER_ID ? DriveApp.getFolderById(FOLDER_ID) : DriveApp.getRootFolder();
}

function json_(payload) {
  return ContentService
    .createTextOutput(JSON.stringify(payload))
    .setMimeType(ContentService.MimeType.JSON);
}

function authorize_(params) {
  if (!BERNIE_SECRET) return;
  if (String(params && params.secret) !== BERNIE_SECRET) {
    throw new Error('Unauthorized: the shared secret did not match.');
  }
}

/** GET lists the folder: ?secret=...&limit=50 */
function doGet(e) {
  try {
    var params = (e && e.parameter) || {};
    authorize_(params);

    var limit = Number(params.limit || 50);
    var files = folder_().getFiles();
    var rows = [];
    while (files.hasNext() && rows.length < limit) {
      var file = files.next();
      rows.push({
        id: file.getId(),
        name: file.getName(),
        mime_type: file.getMimeType(),
        size_bytes: file.getSize(),
        modified_time: file.getLastUpdated().toISOString(),
        link: file.getUrl()
      });
    }
    return json_({ ok: true, rows: rows, count: rows.length });
  } catch (err) {
    return json_({ ok: false, error: String(err && err.message ? err.message : err) });
  }
}

/**
 * POST writes the rows into the folder.
 *   { secret, name: 'export.json', format: 'json' | 'csv', rows: [ {...} ] }
 */
function doPost(e) {
  try {
    var body = {};
    if (e && e.postData && e.postData.contents) {
      body = JSON.parse(e.postData.contents);
    }
    authorize_(body);

    var rows = body.rows || [];
    if (!rows.length) return json_({ ok: false, error: 'No rows supplied.' });

    var format = String(body.format || 'json');
    var name = String(body.name || (format === 'csv' ? 'export.csv' : 'export.json'));

    var contents;
    var mime;
    if (format === 'csv') {
      var headers = [];
      rows.forEach(function (row) {
        Object.keys(row).forEach(function (key) {
          if (headers.indexOf(key) === -1) headers.push(key);
        });
      });
      var lines = [headers.join(',')];
      rows.forEach(function (row) {
        lines.push(headers.map(function (header) {
          var value = row[header];
          if (value === null || value === undefined) value = '';
          return '"' + String(value).replace(/"/g, '""') + '"';
        }).join(','));
      });
      contents = lines.join('\\n');
      mime = MimeType.CSV;
    } else {
      contents = JSON.stringify(rows, null, 2);
      mime = MimeType.PLAIN_TEXT;
    }

    var file = folder_().createFile(name, contents, mime);
    return json_({
      ok: true,
      rows: [{ id: file.getId(), name: file.getName(), link: file.getUrl() }],
      written: rows.length
    });
  } catch (err) {
    return json_({ ok: false, error: String(err && err.message ? err.message : err) });
  }
}
`;
}

