/* Supabase, via an Edge Function                                             */
/* -------------------------------------------------------------------------- */

function supabaseEdgeFunction(options: CompanionOptions, secret: string): string {
  const table = options.table || 'rows';
  const onConflict = options.onConflict || '';

  return `/**
 * Bernie companion Edge Function for Supabase.
 *
 * Deploy this and the service role key stays on Supabase's servers: Bernie
 * posts rows to this function, which writes them with elevated rights. That
 * keeps a privileged key out of the browser entirely.
 *
 * Generated by Bernie. Safe to edit.
 */

import { createClient } from 'jsr:@supabase/supabase-js@2';

// Set with: supabase secrets set BERNIE_SECRET=...
const BERNIE_SECRET = Deno.env.get('BERNIE_SECRET') ?? ${JSON.stringify(secret)};

// Injected automatically in the Edge Function runtime.
const SUPABASE_URL = Deno.env.get('SUPABASE_URL')!;
const SERVICE_ROLE_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;

const DEFAULT_TABLE = ${JSON.stringify(table)};
const DEFAULT_ON_CONFLICT = ${JSON.stringify(onConflict)};

const client = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, {
  auth: { persistSession: false },
});

interface RequestBody {
  secret?: string;
  action?: 'insert' | 'upsert' | 'select' | 'update' | 'delete';
  table?: string;
  rows?: Record<string, unknown>[];
  onConflict?: string;
  /** PostgREST-style filters, e.g. { status: 'eq.active' } */
  filters?: Record<string, string>;
  select?: string;
  limit?: number;
  order?: { column: string; ascending?: boolean };
}

function json(payload: unknown, status = 200): Response {
  return new Response(JSON.stringify(payload), {
    status,
    headers: { 'Content-Type': 'application/json' },
  });
}

/** Applies { column: 'op.value' } filters to a PostgREST query builder. */
function applyFilters(query: any, filters?: Record<string, string>) {
  Object.entries(filters ?? {}).forEach(([column, expression]) => {
    const dot = expression.indexOf('.');
    if (dot <= 0) return;
    const op = expression.slice(0, dot);
    const value = expression.slice(dot + 1);
    if (typeof query[op] === 'function') {
      query = query[op](column, value);
    }
  });
  return query;
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response('ok', {
      headers: {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Headers': 'content-type',
        'Access-Control-Allow-Methods': 'POST, OPTIONS',
      },
    });
  }

  if (req.method !== 'POST') {
    return json({ ok: false, error: 'Use POST.' }, 405);
  }

  let body: RequestBody;
  try {
    body = await req.json();
  } catch {
    return json({ ok: false, error: 'Body was not valid JSON.' }, 400);
  }

  if (BERNIE_SECRET && body.secret !== BERNIE_SECRET) {
    return json({ ok: false, error: 'Unauthorized: the shared secret did not match.' }, 401);
  }

  const table = body.table || DEFAULT_TABLE;
  const action = body.action ?? 'insert';

  try {
    if (action === 'select') {
      let query = client.from(table).select(body.select ?? '*');
      query = applyFilters(query, body.filters);
      if (body.order) query = query.order(body.order.column, { ascending: body.order.ascending ?? true });
      if (body.limit) query = query.limit(body.limit);

      const { data, error } = await query;
      if (error) return json({ ok: false, error: error.message }, 400);
      return json({ ok: true, rows: data ?? [], count: data?.length ?? 0 });
    }

    if (action === 'delete') {
      if (!body.filters || Object.keys(body.filters).length === 0) {
        return json({ ok: false, error: 'Refusing to delete without a filter.' }, 400);
      }
      const { data, error } = await applyFilters(client.from(table).delete(), body.filters).select();
      if (error) return json({ ok: false, error: error.message }, 400);
      return json({ ok: true, rows: data ?? [], deleted: data?.length ?? 0 });
    }

    const rows = body.rows ?? [];
    if (rows.length === 0) return json({ ok: false, error: 'No rows supplied.' }, 400);

    if (action === 'update') {
      if (!body.filters || Object.keys(body.filters).length === 0) {
        return json({ ok: false, error: 'Refusing to update without a filter.' }, 400);
      }
      const { data, error } = await applyFilters(client.from(table).update(rows[0]), body.filters).select();
      if (error) return json({ ok: false, error: error.message }, 400);
      return json({ ok: true, rows: data ?? [], updated: data?.length ?? 0 });
    }

    if (action === 'upsert') {
      const onConflict = body.onConflict || DEFAULT_ON_CONFLICT;
      const { data, error } = await client
        .from(table)
        .upsert(rows, onConflict ? { onConflict } : undefined)
        .select();
      if (error) return json({ ok: false, error: error.message }, 400);
      return json({ ok: true, rows: data ?? [], written: data?.length ?? rows.length });
    }

    const { data, error } = await client.from(table).insert(rows).select();
    if (error) return json({ ok: false, error: error.message }, 400);
    return json({ ok: true, rows: data ?? [], written: data?.length ?? rows.length });
  } catch (err) {
    return json({ ok: false, error: err instanceof Error ? err.message : String(err) }, 500);
  }
});
`;
}

